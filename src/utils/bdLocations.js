// একই ইংরেজি নামের বাংলা জেলাভেদে আলাদা হলে এখানে ("জেলা/উপজেলা")
const BN_UPAZILA_OVERRIDES = {
  "Narail/Lohagara": "লোহাগড়া",
};

function bnUpazila(district, en) {
  const special = BN_UPAZILA_OVERRIDES[`${district}/${en}`];
  if (special) return special;
  if (BN_UPAZILAS[en]) return BN_UPAZILAS[en];
  if (en.endsWith(" Sadar")) {
    return `${BN_DISTRICTS[district] || en.replace(" Sadar", "")} সদর`;
  }
  return en;
}

// জেলার নাম (ইংরেজি/বাংলা) দিলে [{ en, bn }] লিস্ট ফেরত দেয়
export function getUpazilaOptions(district) {
  const name = resolveDistrict(district);
  if (!name) return [];
  return UPAZILAS[name].map((en) => ({ en, bn: bnUpazila(name, en) }));
}

// উপজেলার সাজেশন বাছাই: ঘর খালি থাকলে, বা ঘরে জেলার নাম/পুরো উপজেলার নাম
// থাকলে সব দেখায়; নইলে ইংরেজি বা বাংলা যেকোনো অংশ মিললে দেখায়
export function upazilaMatches(option, text) {
  const raw = (text || "").trim();
  if (!raw) return true;
  if (resolveDistrict(raw)) return true;

  const q = raw.toLowerCase();
  if (option.en.toLowerCase() === q || option.bn === raw) return true;

  return option.en.toLowerCase().includes(q) || option.bn.includes(raw);
}

// "উপজেলা, জেলা" আকারে দেখানোর জন্য (উপজেলা না থাকলে শুধু জেলা)
// পুরনো ডোনারদের উপজেলার ঘরে জেলার নামই আছে, ওটা দুইবার দেখানো হয় না
export function placeText(upazila, district) {
  const u = (upazila || "").trim();
  const d = (district || "").trim();

  if (u && d && u.toLowerCase() === d.toLowerCase()) return d;

  return [u, d].filter(Boolean).join(", ");
}

// সার্চের আগে জেলার নাম ইংরেজিতে বদলে নেয় (বাংলা/অন্য বানান হলে)।
// পুরো নাম না মিললে (যেমন অর্ধেক লেখা) যা লেখা আছে তাই ফেরত দেয়।
export function normalizeDistrict(text) {
  const raw = (text || "").trim();
  return resolveDistrict(raw) || raw;
}

