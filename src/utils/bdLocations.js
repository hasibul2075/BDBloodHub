// ইংরেজি বা বাংলা যেকোনো নাম থেকে ইংরেজি জেলার নাম বের করে (না পেলে "")
function resolveDistrict(input) {
  const raw = (input || "").trim();
  if (!raw) return "";
  const key = raw.toLowerCase();

  const exact = Object.keys(UPAZILAS).find((d) => d.toLowerCase() === key);
  if (exact) return exact;
  if (ALIASES[key]) return ALIASES[key];
  if (BN_ALIASES[raw]) return BN_ALIASES[raw];

  return Object.keys(BN_DISTRICTS).find((d) => BN_DISTRICTS[d] === raw) || "";
}

// জেলার নাম (ইংরেজি/বাংলা) দিলে উপজেলার লিস্ট ফেরত দেয় (না পেলে খালি লিস্ট)
export function getUpazilas(district) {
  const name = resolveDistrict(district);
  return name ? UPAZILAS[name] : [];
}

// জেলার সাজেশন বাছাইয়ের জন্য: ইংরেজি বা বাংলা যেকোনো অংশ মিললেই true
export function districtMatches(district, text) {
  const q = (text || "").trim().toLowerCase();
  if (!q) return false;
  return (
    district.toLowerCase().includes(q) ||
    (BN_DISTRICTS[district] || "").includes(q)
  );
}

